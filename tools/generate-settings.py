"""Generate typed native scalar settings bindings from the pinned source.
Run with the native source root. Output stays in that source worktree.
Sources are consumer references, not claims that every setting can apply live.
"""
from pathlib import Path
import re
import sys
import json

root = Path(sys.argv[1]).resolve()
header = (root / "src/common/settings.h").read_text()
values = header[header.index("struct Values {"):header.index("extern Values values")]
pattern = r"(?:Switchable)?Setting<([^;]+?)>\s+(\w+)\s*\{"
fields = [(m.group(1), m.group(2)) for m in re.finditer(pattern, values)]
live = {"cpu_clock_percentage", "volume", "frame_limit", "turbo_limit",
        "simulate_headphones_plugged", "factor_3d"}
consumers = {}
for directory in ("core", "video_core", "audio_core"):
    for p in sorted((root / "src" / directory).rglob("*.cpp")):
        for line, text in enumerate(p.read_text(errors="replace").splitlines(), 1):
            for field in re.findall(r"(?:Settings::)?values\.(\w+)", text):
                consumers.setdefault(field, []).append(f"{p.relative_to(root).as_posix()}:{line}")
prefix = r"""// Generated by LOTUS tools/generate-settings.py. Do not edit.
#pragma once
#include <functional>
#include <limits>
#include <type_traits>
#include <json.hpp>
#include "common/settings.h"
namespace Settings {
NLOHMANN_DEFINE_TYPE_NON_INTRUSIVE(InputProfile, name, buttons, analogs, motion_device, touch_device,
    controller_touch_device, use_touchpad, use_touch_from_button, touch_from_button_map_index,
    udp_input_address, udp_input_port, udp_pad_index, maptype)
NLOHMANN_DEFINE_TYPE_NON_INTRUSIVE(TouchFromButtonMap, name, buttons)
}
namespace CtrWorker {
using SettingsJson = nlohmann::json;
struct SettingBinding {
    const char* name;
    const char* apply;
    const char* source;
    std::function<SettingsJson()> get;
    std::function<SettingsJson()> defaults;
    std::function<void(const SettingsJson&)> set;
    SettingsJson range, choices;
};
template<class T> SettingsJson SettingJson(const T& value) {
    if constexpr (std::is_enum_v<T>) return static_cast<std::underlying_type_t<T>>(value);
    else return value;
}
template<class S> SettingBinding BindSetting(const char* name, S& setting,
                                             const char* apply, const char* source) {
    using T = std::decay_t<decltype(setting.GetValue())>;
    return {name, apply, source, [&setting] { return SettingJson(setting.GetValue()); },
        [&setting] { return SettingJson(setting.GetDefault()); },
        [&setting](const SettingsJson& j) {
            if constexpr (std::is_same_v<T, bool>) {
                if (!j.is_boolean()) throw std::invalid_argument("expected boolean");
            } else if constexpr (std::is_integral_v<T> || std::is_enum_v<T>) {
                if (!j.is_number_integer()) throw std::invalid_argument("expected integer");
                if constexpr (std::is_integral_v<T>) {
                    const auto number = j.get<long double>();
                    if (number < std::numeric_limits<T>::lowest() ||
                        number > std::numeric_limits<T>::max())
                        throw std::invalid_argument("integer out of range");
                }
            } else if constexpr (std::is_floating_point_v<T>) {
                if (!j.is_number()) throw std::invalid_argument("expected number");
            } else if constexpr (std::is_same_v<T, std::string>) {
                if (!j.is_string() || j.get_ref<const std::string&>().size() > 4096)
                    throw std::invalid_argument("expected bounded string");
            }
            const auto old = setting.GetValue();
            const auto value = j.get<T>();
            setting.SetValue(value);
            if (setting.GetValue() != value) {
                setting.SetValue(old);
                throw std::invalid_argument("setting out of range");
            }
        }, setting.GetRange() ? SettingsJson{{"min", SettingJson(setting.GetRange()->first)},
                                              {"max", SettingJson(setting.GetRange()->second)}} : SettingsJson(nullptr),
        nullptr};
}
template<class T> SettingBinding BindRaw(const char* name, T& value, const char* apply, const char* source) {
    const T defaults = value;
    return {name, apply, source, [&value] { return SettingsJson(value); },
        [defaults] { return SettingsJson(defaults); },
        [&value](const SettingsJson& j) {
            if (j.dump().size() > 8192) throw std::invalid_argument("setting exceeds budget");
            if constexpr (std::is_same_v<T, bool>) {
                if (!j.is_boolean()) throw std::invalid_argument("expected boolean");
            } else if constexpr (std::is_integral_v<T>) {
                if (!j.is_number_integer() || j.get<long double>() < std::numeric_limits<T>::lowest() ||
                    j.get<long double>() > std::numeric_limits<T>::max())
                    throw std::invalid_argument("integer out of range");
            }
            value = j.get<T>();
        }, nullptr, nullptr};
}
inline std::vector<SettingBinding> SettingsBindings() {
    std::vector<SettingBinding> result;
"""
lines = [prefix]
for typ, name in fields:
    apply = "live" if name in live else "boot"
    sources = consumers.get(name, ["src/common/settings.h"])
    source = ";".join(sources[:6])
    lines.append(f'    result.push_back(BindSetting("{name}", Settings::values.{name}, "{apply}", {json.dumps(source)}));\n')
# Raw Values entries used by native consumers (Qt-only field stays excluded).
raw_fields = {
    "audio_muted": "live", "record_frame_times": "boot", "lle_modules": "boot",
    "camera_name": "boot", "camera_config": "boot", "camera_flip": "boot",
    "output_format": "boot", "format_options": "boot", "video_encoder": "boot",
    "video_encoder_options": "boot", "video_bitrate": "boot", "audio_encoder": "boot",
    "audio_encoder_options": "boot", "audio_bitrate": "boot",
    "current_input_profile_index": "boot", "current_input_profile": "boot",
    "input_profiles": "boot", "touch_from_button_maps": "boot",
}
for name, apply in raw_fields.items():
    source = ";".join(consumers.get(name, ["src/common/settings.h"])[:6])
    lines.append(f'    result.push_back(BindRaw("{name}", Settings::values.{name}, "{apply}", {json.dumps(source)}));\n')
# Attach legal enum values to every typed enum, including enum arrays.
enum_sources = [("Settings::", header),
                ("AudioCore::", (root / "src/audio_core/sink_details.h").read_text()),
                ("AudioCore::", (root / "src/audio_core/input_details.h").read_text())]
for namespace, source in enum_sources:
    source = re.sub(r"//[^\n]*", "", source)
    for match in re.finditer(r"enum class\s+(\w+)[^{]*\{([^}]+)\}", source):
        enum, body = match.groups()
        choices = []
        for entry in body.split(","):
            entry = re.sub(r"#[^\n]*", "", entry).strip()
            name = entry.split("=")[0].strip()
            if not re.fullmatch(r"\w+", name) or name in ("LibRetro", "Count", "NumLayouts"):
                continue
            choices.append(f"static_cast<int>({namespace}{enum}::{name})")
        for typ, name in fields:
            if typ.split(",")[0].strip() in (enum, namespace+enum):
                lines.append(f'    for (auto& b : result) if (std::string(b.name) == "{name}") b.choices = SettingsJson::array({{{", ".join(choices)}}});\n')
lines.append("    return result;\n}\n} // namespace CtrWorker\n")
(root / "src/ctr_worker/settings_bindings.h").write_text("".join(lines))
print(f"generated {len(fields)+len(raw_fields)} typed settings bindings")
