//! Generated contract for the shared CLI, MCP and desktop debug-command parser.
pub fn schema() -> serde_json::Value {
    serde_json::to_value(schemars::schema_for!(crate::debug::DebugCommand))
        .expect("schema serializes")
}
pub fn operations() -> Vec<String> {
    let schema = schema();
    let mut names = schema["oneOf"]
        .as_array()
        .expect("tagged command union")
        .iter()
        .map(|command| {
            command["properties"]["operation"]["const"]
                .as_str()
                .expect("operation tag")
                .to_string()
        })
        .collect::<Vec<_>>();
    names.sort();
    names
}
pub fn parity() -> String {
    let mut text=String::from("# 32 — Generated debugger command parity\n\nGenerated by `cargo run -p lotus-protocol --example export-debug`.\nAll commands use the shared typed parser and Supervisor dispatch.\nThis table records reachability, not native-backend acceptance.\n\n| Operation | CLI JSON line | MCP tool |\n| --- | --- | --- |\n");
    for name in operations() {
        text += &format!("| `{name}` | `ctr-cli debug`: `{name}` | `lotus_debug`: `{name}` |\n");
    }
    text+="\nWorker-envelope routes: hello is negotiated when creating a session; status,\nload, reset, stop, continue (run), advance (run_until), capture_scaled\n(capture), input_state (input), read_memory and registers are available above.\n\nRuntime bounds are additionally enforced by `DebugCommand::validate`.\n";
    text
}

#[cfg(test)]
mod tests {
    #[test]
    fn checked_in_schema_and_surface_table_match_the_typed_contract() {
        let root = std::path::Path::new(env!("CARGO_MANIFEST_DIR")).join("../..");
        let stored: serde_json::Value = serde_json::from_str(
            &std::fs::read_to_string(root.join("specs/debug-v1.schema.json"))
                .expect("regenerate debug schema"),
        )
        .expect("stored schema");
        assert_eq!(
            stored,
            super::schema(),
            "run export-debug to update the public contract"
        );
        assert_eq!(
            std::fs::read_to_string(root.join("docs/32-debugger-command-parity.md"))
                .expect("parity table"),
            super::parity()
        );
    }
}
